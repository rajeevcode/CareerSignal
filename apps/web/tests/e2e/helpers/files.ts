export function pdfUpload(name = 'cv.pdf') {
  return { name, mimeType: 'application/pdf', buffer: makePdfBuffer() };
}
export function docxUpload(name = 'cv.docx') {
  return {
    name,
    mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    buffer: makeDocxBuffer(),
  };
}
